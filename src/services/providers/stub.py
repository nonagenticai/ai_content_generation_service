"""Deterministic stub video provider.

Produces a real H.264/MP4 video clip via ffmpeg. The output is parseable
by ffprobe and consumable by ``video_production_service``'s compilation
pipeline (which expects libx264/yuv420p MP4 -- see
``video_production_service/src/services/ffmpeg_ops.py``).

Activated via ``VIDEO_PROVIDER=stub``. Intended for offline pipelines
(CI, demos, local dev) without paid APIs. Generated bytes are cached
in-memory per (width, height, duration) so repeated calls are free.
"""

from __future__ import annotations

import asyncio
import hashlib
import logging
import shutil
import subprocess  # nosec B404 -- ffmpeg invocation with fully controlled args, no shell
import tempfile
import uuid
from pathlib import Path
from threading import Lock
from typing import Any

from src.services.providers.base import VideoGenerationProvider

logger = logging.getLogger(__name__)

_DEFAULT_WIDTH = 256
_DEFAULT_HEIGHT = 256
_DEFAULT_FPS = 30
_DEFAULT_DURATION_S = 1.0
_FFMPEG_TIMEOUT_S = 60.0
_MP4_FTYP = b"ftyp"


def _color_for_prompt(prompt: str) -> tuple[int, int, int]:
    digest = hashlib.sha256(prompt.encode("utf-8")).digest()
    return digest[0], digest[1], digest[2]


def _hex_color(rgb: tuple[int, int, int]) -> str:
    return "0x{:02x}{:02x}{:02x}".format(*rgb)


def _render_mp4(
    *,
    width: int,
    height: int,
    duration_s: float,
    prompt: str,
    fps: int = _DEFAULT_FPS,
) -> bytes:
    """Generate a libx264/yuv420p MP4 with a prompt-derived solid color.

    Uses ffmpeg's ``lavfi`` color source -- no input files needed.
    """
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        raise RuntimeError(
            "ffmpeg not found on PATH; the stub video provider requires ffmpeg",
        )
    color = _hex_color(_color_for_prompt(prompt))
    # Even dimensions are required for yuv420p.
    even_w = width if width % 2 == 0 else width + 1
    even_h = height if height % 2 == 0 else height + 1
    with tempfile.TemporaryDirectory() as tmp:
        out_path = Path(tmp) / "stub.mp4"
        cmd = [
            ffmpeg,
            "-y",
            "-f",
            "lavfi",
            "-i",
            f"color=c={color}:s={even_w}x{even_h}:r={fps}:d={duration_s:.3f}",
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            "-preset",
            "ultrafast",
            "-tune",
            "stillimage",
            "-movflags",
            "+faststart",
            "-an",
            str(out_path),
        ]
        try:
            result = subprocess.run(  # noqa: S603  # nosec B603 -- argv list, no shell, ffmpeg path resolved via shutil.which
                cmd,
                capture_output=True,
                text=True,
                timeout=_FFMPEG_TIMEOUT_S,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError(f"ffmpeg timed out after {_FFMPEG_TIMEOUT_S}s") from exc
        if result.returncode != 0:
            stderr_tail = (result.stderr or "")[-512:]
            raise RuntimeError(f"ffmpeg failed (rc={result.returncode}): {stderr_tail}")
        data = out_path.read_bytes()
    if _MP4_FTYP not in data[:32]:
        raise RuntimeError("ffmpeg produced output without an MP4 ftyp box")
    return data


class StubVideoProvider(VideoGenerationProvider):
    """Deterministic video provider that emits real H.264/MP4 bytes."""

    name = "stub"

    def __init__(
        self,
        *,
        default_width: int = _DEFAULT_WIDTH,
        default_height: int = _DEFAULT_HEIGHT,
        default_duration_s: float = _DEFAULT_DURATION_S,
        delay_s: float = 0.0,
    ) -> None:
        self._default_width = default_width
        self._default_height = default_height
        self._default_duration_s = default_duration_s
        self._delay_s = delay_s
        # In-memory cache keyed by (width, height, duration_s, prompt).
        # Per task spec: cache per resolution, in-memory.
        self._cache: dict[tuple[int, int, float, str], bytes] = {}
        self._cache_lock = Lock()
        self._pending: dict[str, dict] = {}

    def _params_from_kwargs(self, kwargs: dict) -> tuple[int, int, float, str]:
        width = int(kwargs.get("width") or self._default_width)
        height = int(kwargs.get("height") or self._default_height)
        duration_s = float(kwargs.get("duration_s") or self._default_duration_s)
        prompt = str(kwargs.get("_prompt", ""))
        return width, height, duration_s, prompt

    def _get_or_render(self, width: int, height: int, duration_s: float, prompt: str) -> bytes:
        key = (width, height, round(duration_s, 3), prompt)
        with self._cache_lock:
            cached = self._cache.get(key)
            if cached is not None:
                return cached
        data = _render_mp4(width=width, height=height, duration_s=duration_s, prompt=prompt)
        with self._cache_lock:
            self._cache.setdefault(key, data)
        return data

    async def submit(self, prompt: str, **kwargs: Any) -> str:
        if self._delay_s > 0:
            await asyncio.sleep(self._delay_s)
        task_id = str(uuid.uuid7())
        self._pending[task_id] = {**kwargs, "_prompt": prompt}
        logger.info("Stub video submit: task_id=%s prompt=%s", task_id, prompt[:80])
        return task_id

    async def check_status(self, task_id: str) -> dict:
        return {
            "status": "completed",
            "video_url": f"stub://video/{task_id}.mp4",
            "error": None,
        }

    async def download(self, task_id: str, video_url: str) -> bytes:
        del video_url
        kwargs = self._pending.pop(task_id, {})
        width, height, duration_s, prompt = self._params_from_kwargs(kwargs)
        # Render in a thread to avoid blocking the event loop on ffmpeg.
        return await asyncio.to_thread(self._get_or_render, width, height, duration_s, prompt)

    def estimate_cost(self, duration_s: float) -> float:
        del duration_s
        return 0.0

    async def health_check(self) -> bool:
        return shutil.which("ffmpeg") is not None

    def get_models(self) -> list[str]:
        return ["stub-v1"]

    def get_styles(self) -> list[str]:
        return ["default"]

    def get_max_duration_s(self) -> float | None:
        return 60.0

    def supports_image_to_video(self) -> bool:
        # The stub ignores the reference image but still accepts the request,
        # so the orchestrator can route image-to-video calls here in offline mode.
        return True
